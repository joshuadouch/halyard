// Package render turns Halyard objects into HAProxy and keepalived config.
package render

import (
	"crypto/hmac"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"net"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/joshuadouch/halyard/internal/config"
	"github.com/joshuadouch/halyard/internal/model"
	"github.com/joshuadouch/halyard/internal/store"
)

// Paths are the files the rendered HAProxy config refers to.
type Paths struct {
	CertDir       string // <id>.pem bundles, default.pem fallback
	MapDir        string // crt-lists and ACL files
	CloudflareIPs string
	SelfIPs       string
	AOPCA         string // Cloudflare origin-pull CA
}

// DefaultPaths derives Paths from the data dir.
func DefaultPaths(c *config.Config) Paths {
	return Paths{
		CertDir:       c.Path("certs"),
		MapDir:        c.Path("haproxy"),
		CloudflareIPs: c.Path("haproxy", "cloudflare-ips.txt"),
		SelfIPs:       c.Path("haproxy", "self-ips.txt"),
		AOPCA:         c.Path("haproxy", "origin-pull-ca.pem"),
	}
}

// Input is everything needed to render.
type Input struct {
	Snap       store.Snapshot
	Config     *config.Config
	Cloudflare model.CloudflareSettings
	Paths      Paths
}

// Output is the rendered configuration.
type Output struct {
	HAProxy    string
	Keepalived string
	// Files maps absolute path -> content for crt-lists and helper files.
	Files map[string]string
}

type listener struct {
	vip   model.VIP
	port  int
	kind  string // http, https, tcp
	hosts []model.Host
}

// Render produces HAProxy and keepalived configuration.
func Render(in Input) (*Output, error) {
	out := &Output{Files: map[string]string{}}
	vips := map[string]model.VIP{}
	for _, v := range in.Snap.VIPs {
		vips[v.ID] = v
	}
	pools := map[string]model.Pool{}
	poolNames := map[string]bool{}
	for _, p := range in.Snap.Pools {
		if poolNames[p.Name] {
			return nil, fmt.Errorf("duplicate pool name %q", p.Name)
		}
		poolNames[p.Name] = true
		pools[p.ID] = p
	}
	acls := map[string]model.AccessList{}
	for _, a := range in.Snap.AccessLists {
		acls[a.ID] = a
	}

	// Group hosts into listeners by VIP + port + kind.
	lmap := map[string]*listener{}
	var keys []string
	add := func(v model.VIP, port int, kind string, h model.Host) {
		k := fmt.Sprintf("%s|%05d|%s", v.IP(), port, kind)
		l, ok := lmap[k]
		if !ok {
			l = &listener{vip: v, port: port, kind: kind}
			lmap[k] = l
			keys = append(keys, k)
		}
		l.hosts = append(l.hosts, h)
	}
	seenName := map[string]string{} // vip|port|hostname -> host id
	for _, h := range in.Snap.Hosts {
		if !h.Enabled {
			continue
		}
		v, ok := vips[h.VIPID]
		if !ok {
			return nil, fmt.Errorf("host %s uses a VIP that no longer exists", label(h))
		}
		for _, r := range h.Routes {
			p, ok := pools[r.PoolID]
			if !ok {
				return nil, fmt.Errorf("host %s routes to a pool that no longer exists", label(h))
			}
			if p.Mode != h.Mode {
				return nil, fmt.Errorf("host %s is %s but pool %s is %s", label(h), h.Mode, p.Name, p.Mode)
			}
		}
		if h.AccessListID != "" {
			a, ok := acls[h.AccessListID]
			if !ok {
				return nil, fmt.Errorf("host %s uses an access list that no longer exists", label(h))
			}
			if h.Mode == model.ModeTCP && len(a.Users) > 0 {
				return nil, fmt.Errorf("host %s is TCP, which cannot ask for a password; access list %s has users", label(h), a.Name)
			}
		}
		if h.Mode == model.ModeTCP {
			add(v, h.TCPPort, "tcp", h)
			continue
		}
		for _, pk := range []struct {
			port int
			kind string
		}{{h.HTTPPort, "http"}, {h.HTTPSPort, "https"}} {
			if pk.port == 0 {
				continue
			}
			for _, n := range h.Hostnames {
				k := fmt.Sprintf("%s|%d|%s", v.IP(), pk.port, n)
				if other, dup := seenName[k]; dup && other != h.ID {
					return nil, fmt.Errorf("hostname %s is used twice on %s:%d", n, v.IP(), pk.port)
				}
				seenName[k] = h.ID
			}
			add(v, pk.port, pk.kind, h)
		}
	}
	sort.Strings(keys)
	// Port clashes between kinds on the same IP.
	portKind := map[string]string{}
	for _, k := range keys {
		l := lmap[k]
		pk := fmt.Sprintf("%s:%d", l.vip.IP(), l.port)
		if prev, ok := portKind[pk]; ok && prev != l.kind {
			return nil, fmt.Errorf("%s is used for both %s and %s", pk, prev, l.kind)
		}
		portKind[pk] = l.kind
		if l.kind == "tcp" && len(l.hosts) > 1 {
			return nil, fmt.Errorf("%s is used by more than one TCP host", pk)
		}
	}

	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	hc := in.Config.HAProxy
	w("# Generated by Halyard. Do not edit: changes are overwritten on the next apply.")
	w("global")
	w("    log /dev/log local0")
	w("    log /dev/log local1 notice")
	w("    user haproxy")
	w("    group haproxy")
	w("    stats socket %s mode 660 level admin expose-fd listeners", hc.Socket)
	w("    stats timeout 30s")
	if hc.StateFile != "" {
		w("    server-state-file %s", hc.StateFile)
	}
	w("    ssl-default-bind-options ssl-min-ver TLSv1.2 no-tls-tickets")
	w("    ssl-default-bind-ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305")
	w("    ssl-default-bind-ciphersuites TLS_AES_128_GCM_SHA256:TLS_AES_256_GCM_SHA384:TLS_CHACHA20_POLY1305_SHA256")
	w("    ssl-default-server-options ssl-min-ver TLSv1.2")
	w("")
	w("defaults")
	w("    log global")
	w("    mode http")
	w("    option httplog")
	w("    option dontlognull")
	w("    timeout connect 5s")
	w("    timeout client 60s")
	w("    timeout server 60s")
	w("    timeout http-request 10s")
	w("    timeout http-keep-alive 10s")
	w("    timeout queue 30s")
	w("    timeout tunnel 1h")
	w("    timeout client-fin 30s")
	if hc.StateFile != "" {
		w("    load-server-state-from-file global")
	}
	w("    default-server init-addr last,libc,none")
	w("")
	for _, a := range in.Snap.AccessLists {
		if len(a.Users) == 0 {
			continue
		}
		w("userlist %s", userlistName(a))
		for _, u := range a.Users {
			w("    user %s password %s", u.Username, u.PasswordHash)
		}
		w("")
	}
	if hc.StatsListen != "" {
		w("frontend halyard_stats")
		w("    bind %s", hc.StatsListen)
		w("    http-request use-service prometheus-exporter if { path /metrics }")
		w("    stats enable")
		w("    stats uri /stats")
		w("    stats refresh 10s")
		w("    no log")
		w("")
	}

	for _, k := range keys {
		l := lmap[k]
		name := fmt.Sprintf("fe_%s_%d", strings.NewReplacer(".", "_", ":", "_").Replace(l.vip.IP()), l.port)
		addr := l.vip.IP()
		if strings.Contains(addr, ":") {
			addr = "[" + addr + "]"
		}
		switch l.kind {
		case "tcp":
			h := l.hosts[0]
			p := pools[h.Routes[0].PoolID]
			w("frontend %s", name)
			w("    mode tcp")
			w("    option tcplog")
			w("    bind %s:%d", addr, l.port)
			if len(h.AllowCIDRs) > 0 {
				w("    tcp-request connection reject if !{ src %s }", strings.Join(h.AllowCIDRs, " "))
			}
			if a, ok := acls[h.AccessListID]; ok && len(a.AllowCIDRs) > 0 {
				w("    tcp-request connection reject if !{ src %s }", strings.Join(a.AllowCIDRs, " "))
			}
			w("    default_backend %s", beName(p))
			w("")
		case "http", "https":
			w("frontend %s", name)
			w("    mode http")
			if l.kind == "https" {
				crt := filepath.Join(in.Paths.MapDir, fmt.Sprintf("crtlist_%s_%d.txt", sanitize(l.vip.IP()), l.port))
				out.Files[crt] = crtList(l, in)
				w("    bind %s:%d ssl crt-list %s alpn h2,http/1.1", addr, l.port, crt)
			} else {
				w("    bind %s:%d", addr, l.port)
			}
			w("    http-request set-var(txn.host) req.hdr(host),field(1,:),lower")
			if in.Cloudflare.RealIP {
				w("    acl from_cf src -f %s", in.Paths.CloudflareIPs)
				w("    acl from_self src -f %s", in.Paths.SelfIPs)
				w("    acl has_cf_ip req.hdr(CF-Connecting-IP) -m found")
				w("    http-request set-src req.hdr(CF-Connecting-IP) if has_cf_ip from_cf")
				w("    http-request set-src req.hdr(CF-Connecting-IP) if has_cf_ip from_self")
			}
			if l.kind == "https" {
				w("    http-request set-header X-Forwarded-Proto https")
			} else {
				w("    http-request set-header X-Forwarded-Proto http")
			}
			w("    http-request set-header X-Real-IP %%[src]")
			for _, h := range l.hosts {
				acl := "h_" + sanitize(h.ID)
				w("    # %s", label(h))
				var exact []string
				for _, n := range h.Hostnames {
					if strings.HasPrefix(n, "*.") {
						w("    acl %s var(txn.host) -m end %s", acl, n[1:])
					} else {
						exact = append(exact, n)
					}
				}
				if len(exact) > 0 {
					w("    acl %s var(txn.host) -m str %s", acl, strings.Join(exact, " "))
				}
				if l.kind == "http" && h.ForceHTTPS {
					if h.HTTPSPort == 443 {
						w("    http-request redirect scheme https code 301 if %s", acl)
					} else {
						w("    http-request redirect prefix https://%%[var(txn.host)]:%d code 301 if %s", h.HTTPSPort, acl)
					}
					continue
				}
				if len(h.AllowCIDRs) > 0 {
					w("    http-request deny deny_status 403 if %s !{ src %s }", acl, strings.Join(h.AllowCIDRs, " "))
				}
				if l.kind == "https" && h.RequireAOP {
					w("    http-request deny deny_status 403 if %s !{ ssl_c_used }", acl)
					w("    http-request deny deny_status 403 if %s !{ ssl_c_verify 0 }", acl)
				}
				if a, ok := acls[h.AccessListID]; ok {
					writeAccess(w, acl, a)
				}
				if l.kind == "https" && h.HSTS {
					w("    http-response set-header Strict-Transport-Security \"max-age=31536000\" if %s", acl)
				}
				for _, r := range h.Routes {
					p := pools[r.PoolID]
					if r.PathPrefix == "" {
						continue
					}
					w("    use_backend %s if %s { path_beg %s }", beName(p), acl, r.PathPrefix)
				}
				for _, r := range h.Routes {
					if r.PathPrefix == "" {
						w("    use_backend %s if %s", beName(pools[r.PoolID]), acl)
					}
				}
			}
			w("    default_backend halyard_notfound")
			w("")
		}
	}

	w("backend halyard_notfound")
	w("    mode http")
	w("    http-request return status 404 content-type text/plain string \"No host is configured for this name.\"")
	w("")

	for _, p := range in.Snap.Pools {
		if err := renderPool(&b, p); err != nil {
			return nil, err
		}
	}
	out.HAProxy = b.String()

	ka, err := renderKeepalived(in)
	if err != nil {
		return nil, err
	}
	out.Keepalived = ka
	return out, nil
}

func userlistName(a model.AccessList) string { return "ul_" + sanitize(a.ID) }

// writeAccess renders an access list's checks for one host's ACL. A client
// with valid credentials has them removed before the request reaches the
// backend.
func writeAccess(w func(string, ...any), acl string, a model.AccessList) {
	ips := strings.Join(a.AllowCIDRs, " ")
	ul := userlistName(a)
	const realm = "http-request auth realm Restricted"
	switch {
	case len(a.Users) == 0:
		w("    http-request deny deny_status 403 if %s !{ src %s }", acl, ips)
	case len(a.AllowCIDRs) == 0:
		w("    %s if %s !{ http_auth(%s) }", realm, acl, ul)
	case a.SatisfyAny:
		w("    %s if %s !{ src %s } !{ http_auth(%s) }", realm, acl, ips, ul)
	default:
		w("    http-request deny deny_status 403 if %s !{ src %s }", acl, ips)
		w("    %s if %s !{ http_auth(%s) }", realm, acl, ul)
	}
	if len(a.Users) > 0 {
		w("    http-request del-header Authorization if %s { http_auth(%s) }", acl, ul)
	}
}

func label(h model.Host) string {
	if len(h.Hostnames) > 0 {
		return h.Hostnames[0]
	}
	return h.ID
}

var unsafe = regexp.MustCompile(`[^a-zA-Z0-9_]`)

func sanitize(s string) string { return unsafe.ReplaceAllString(s, "_") }

func beName(p model.Pool) string { return BackendName(p.Name) }

// BackendName is the HAProxy backend name for a pool.
func BackendName(pool string) string { return "be_" + sanitize(pool) }

// ServerName is the HAProxy server name for a pool member.
func ServerName(member string) string { return sanitize(member) }

// crtList builds the crt-list for an HTTPS listener. Hosts that require
// Authenticated Origin Pulls get their own SNI lines that request (and verify
// against the Cloudflare CA) a client certificate.
func crtList(l *listener, in Input) string {
	var b strings.Builder
	certs := map[string]model.Certificate{}
	for _, c := range in.Snap.Certs {
		if c.CertPEM != "" && c.KeyPEM != "" {
			certs[c.ID] = c
		}
	}
	certPath := func(id string) string { return filepath.Join(in.Paths.CertDir, id+".pem") }
	// The first line is the default certificate for clients without SNI.
	fmt.Fprintf(&b, "%s\n", filepath.Join(in.Paths.CertDir, "default.pem"))
	aop := fmt.Sprintf("[verify optional ca-file %s]", in.Paths.AOPCA)
	for _, h := range l.hosts {
		for _, n := range h.Hostnames {
			c, ok := pickCert(h, n, certs, in.Snap.Certs)
			if !ok {
				continue
			}
			if h.RequireAOP {
				fmt.Fprintf(&b, "%s %s %s\n", certPath(c.ID), aop, n)
			} else {
				fmt.Fprintf(&b, "%s %s\n", certPath(c.ID), n)
			}
		}
	}
	return b.String()
}

func pickCert(h model.Host, name string, certs map[string]model.Certificate, ordered []model.Certificate) (model.Certificate, bool) {
	if h.CertificateID != "" {
		c, ok := certs[h.CertificateID]
		return c, ok
	}
	// Exact match first, then wildcard.
	for _, c := range ordered {
		if _, ok := certs[c.ID]; !ok {
			continue
		}
		for _, d := range c.Domains {
			if d == name {
				return c, true
			}
		}
	}
	for _, c := range ordered {
		if _, ok := certs[c.ID]; !ok {
			continue
		}
		for _, d := range c.Domains {
			if MatchWildcard(d, name) {
				return c, true
			}
		}
	}
	return model.Certificate{}, false
}

// MatchWildcard reports whether cert domain d (maybe *.x) covers name.
func MatchWildcard(d, name string) bool {
	d, name = strings.ToLower(d), strings.ToLower(name)
	if !strings.HasPrefix(d, "*.") {
		return d == name
	}
	suffix := d[1:]
	if !strings.HasSuffix(name, suffix) {
		return false
	}
	label := strings.TrimSuffix(name, suffix)
	return label != "" && !strings.Contains(label, ".")
}

// ExpectToHAProxy converts "200", "200,204" or "2xx,3xx" to an http-check expect rule.
func ExpectToHAProxy(s string) (string, error) {
	s = strings.ReplaceAll(strings.TrimSpace(s), " ", "")
	if regexp.MustCompile(`^[1-5][0-9][0-9]$`).MatchString(s) {
		return "status " + s, nil
	}
	var alts []string
	for _, t := range strings.Split(s, ",") {
		switch {
		case regexp.MustCompile(`^[1-5][0-9][0-9]$`).MatchString(t):
			alts = append(alts, t)
		case regexp.MustCompile(`^[1-5]xx$`).MatchString(strings.ToLower(t)):
			alts = append(alts, t[:1]+"[0-9][0-9]")
		default:
			return "", fmt.Errorf("expected status %q: use codes like 200, 200,204 or 2xx,3xx", s)
		}
	}
	return "rstatus ^(" + strings.Join(alts, "|") + ")$", nil
}

var safeToken = regexp.MustCompile(`^[A-Za-z0-9._~:/?#\[\]@!$&'()*+,;=%-]+$`)

func renderPool(b *strings.Builder, p model.Pool) error {
	w := func(format string, a ...any) { fmt.Fprintf(b, format+"\n", a...) }
	w("backend %s", beName(p))
	w("    mode %s", p.Mode)
	w("    balance %s", p.Algorithm)
	if p.Mode == model.ModeHTTP {
		w("    option forwardfor")
	} else {
		w("    option tcplog")
	}
	w("    retries %d", p.Retries)
	w("    option redispatch")
	if p.TimeoutServer > 0 {
		w("    timeout server %ds", p.TimeoutServer)
	}
	switch p.Sticky {
	case "cookie":
		w("    cookie HY_SRV insert indirect nocache httponly")
	case "source":
		w("    stick-table type ip size 200k expire 30m")
		w("    stick on src")
	}
	hc := p.Health
	if hc.Enabled {
		if hc.Type == "http" {
			if !safeToken.MatchString(hc.Path) || !strings.HasPrefix(hc.Path, "/") {
				return fmt.Errorf("pool %s: health check path is invalid", p.Name)
			}
			method := strings.ToUpper(hc.Method)
			if method != "GET" && method != "HEAD" && method != "OPTIONS" {
				return fmt.Errorf("pool %s: health check method must be GET, HEAD or OPTIONS", p.Name)
			}
			w("    option httpchk")
			send := fmt.Sprintf("    http-check send meth %s uri %s ver HTTP/1.1", method, hc.Path)
			if hc.HostHeader != "" {
				if !model.ValidHostname(hc.HostHeader) {
					return fmt.Errorf("pool %s: health check host header is invalid", p.Name)
				}
				send += " hdr Host " + hc.HostHeader
			}
			w("%s", send)
			exp, err := ExpectToHAProxy(hc.ExpectStatus)
			if err != nil {
				return fmt.Errorf("pool %s: %w", p.Name, err)
			}
			w("    http-check expect %s", exp)
		}
		ds := fmt.Sprintf("    default-server inter %ds fall %d rise %d", hc.IntervalSec, hc.Fall, hc.Rise)
		if p.SlowStartSec > 0 {
			ds += fmt.Sprintf(" slowstart %ds", p.SlowStartSec)
		}
		w("%s", ds)
	}
	for _, m := range p.Members {
		host, port, err := net.SplitHostPort(m.Address)
		if err != nil {
			return fmt.Errorf("pool %s member %s: %w", p.Name, m.Name, err)
		}
		if _, err := strconv.Atoi(port); err != nil {
			return fmt.Errorf("pool %s member %s: bad port", p.Name, m.Name)
		}
		if net.ParseIP(host) == nil && !model.ValidHostname(host) {
			return fmt.Errorf("pool %s member %s: bad host", p.Name, m.Name)
		}
		addr := m.Address
		line := fmt.Sprintf("    server %s %s", sanitize(m.Name), addr)
		if hc.Enabled {
			line += " check"
		}
		weight := m.Weight
		if m.State == "drain" {
			weight = 0
		}
		line += fmt.Sprintf(" weight %d", weight)
		if m.Backup {
			line += " backup"
		}
		if m.State == "maint" {
			line += " disabled"
		}
		if p.UpstreamTLS {
			if p.VerifyTLS {
				line += " ssl verify required ca-file @system-ca"
			} else {
				line += " ssl verify none"
			}
			if p.Mode == model.ModeHTTP {
				line += " sni req.hdr(host)"
				if hc.HostHeader != "" {
					line += " check-sni " + hc.HostHeader
				}
			}
		}
		if p.Sticky == "cookie" {
			line += " cookie " + sanitize(m.Name)
		}
		w("%s", line)
	}
	w("")
	return nil
}

// VRRPPassword derives a stable 8-character VRRP password from the secret.
func VRRPPassword(secret string, vrid int) string {
	if secret == "" {
		return "halyard"
	}
	m := hmac.New(sha256.New, []byte(secret))
	fmt.Fprintf(m, "vrrp-%d", vrid)
	return hex.EncodeToString(m.Sum(nil))[:8]
}

func renderKeepalived(in Input) (string, error) {
	c := in.Config
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Generated by Halyard. Do not edit: changes are overwritten on the next apply.")
	w("global_defs {")
	w("    router_id %s", sanitize(c.Node.Name))
	w("    script_user root")
	w("    enable_script_security")
	w("    vrrp_garp_master_delay 1")
	w("    vrrp_garp_master_refresh 60")
	w("}")
	w("")
	w("vrrp_script chk_haproxy {")
	w("    script \"/usr/bin/pgrep -x haproxy\"")
	w("    interval 2")
	w("    fall 2")
	w("    rise 2")
	w("}")
	w("")
	var peerAddrs []string
	for _, p := range c.Cluster.Peers {
		if p.Address != "" {
			peerAddrs = append(peerAddrs, p.Address)
		}
	}
	for _, v := range in.Snap.VIPs {
		preferred := v.PreferredNode
		if preferred == "" && c.IsPrimary() {
			preferred = c.Node.Name
		}
		prio := 100
		if preferred == c.Node.Name {
			prio = 150
		}
		w("vrrp_instance HY_%d {", v.VRID)
		w("    state BACKUP")
		w("    interface %s", v.Interface)
		w("    virtual_router_id %d", v.VRID)
		w("    priority %d", prio)
		w("    advert_int 1")
		if !v.Preempt {
			w("    nopreempt")
		}
		w("    authentication {")
		w("        auth_type PASS")
		w("        auth_pass %s", VRRPPassword(c.Cluster.Secret, v.VRID))
		w("    }")
		if len(peerAddrs) > 0 && c.Node.Address != "" {
			w("    unicast_src_ip %s", c.Node.Address)
			w("    unicast_peer {")
			for _, a := range peerAddrs {
				w("        %s", a)
			}
			w("    }")
		}
		w("    virtual_ipaddress {")
		w("        %s dev %s", v.Address, v.Interface)
		w("    }")
		if v.TrackHAProxy {
			w("    track_script {")
			w("        chk_haproxy")
			w("    }")
		}
		w("}")
		w("")
	}
	return b.String(), nil
}
